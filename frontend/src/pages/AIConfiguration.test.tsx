/**
 * AI Configuration — four states, one gated test form (M23.11/M23.20).
 *
 * What these tests are evidence *for*, and why each is worth writing:
 *
 * * **A state is not an error.** `disabled`, `unreachable` and `model_missing` all
 *   arrive as `200` with a state, so the page must render a badge and a sentence.
 *   If it rendered an error banner, an operator would think the backend had failed
 *   when in fact it had answered correctly.
 * * **The inventory is only asked for when there is one.** `/ai/models` is a real
 *   request that fails when the runtime is down, so it must not be sent while the
 *   status says `runtime_reachable: false`. These tests assert the *absence* of
 *   that call, which is the part a passing render would not catch.
 * * **The test form is gated, not hidden.** It is visible in every state so an
 *   operator can see what it will do, and the button is disabled with the reason
 *   stated. Hidden controls teach nothing.
 * * **The request carries a prompt and nothing else.** `{ prompt }` is asserted
 *   exactly: a `model` or `base_url` field appearing here would mean a browser had
 *   gained the ability to choose what runs.
 * * **Model output is text.** The reply is rendered in a `<pre>` and travels with
 *   its disclaimer; nothing in the page interprets it as markup or as a verdict.
 *
 * Fetch is mocked at the wire through the shared harness, so the client's envelope
 * parsing, the error translation and both hooks run for real.
 */

import { fireEvent, render, screen, waitFor, within } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import type { AiModel, AiModelList, AiStatus, AiTestResult } from '@/types'
import AIConfiguration from '@/pages/AIConfiguration'
import { failure, installFetch, networkDownFetch, ok } from '@/test/harness'

const DISCLAIMER =
  'Generated by a local language model. It may be inaccurate and is not a security verdict.'

/** A status payload with everything settable, defaulting to the `ready` state. */
function status(overrides: Partial<AiStatus> = {}): AiStatus {
  return {
    enabled: true,
    provider: 'ollama',
    model: 'llama3.2:3b',
    state: 'ready',
    state_label: 'Ready',
    state_description: 'The runtime answered and the configured model is installed.',
    runtime_reachable: true,
    model_available: true,
    runtime_version: '0.5.7',
    installed_model_count: 1,
    message: '',
    health_timeout_seconds: 3,
    disclaimer: DISCLAIMER,
    ...overrides,
  }
}

/** One installed model, as the runtime reports it. */
function model(overrides: Partial<AiModel> = {}): AiModel {
  return {
    name: 'llama3.2:3b',
    parameter_size: '3.2B',
    quantization: 'Q4_K_M',
    size_bytes: 2_019_393_189,
    family: 'llama',
    ...overrides,
  }
}

/** A model listing as `GET /ai/models` answers. */
function modelList(
  models: readonly AiModel[],
  overrides: Partial<AiModelList> = {},
): AiModelList {
  return {
    count: models.length,
    configured_model: 'llama3.2:3b',
    configured_model_installed: models.some(entry => entry.name === 'llama3.2:3b'),
    models,
    disclaimer: DISCLAIMER,
    ...overrides,
  }
}

/** A generation payload as `POST /ai/test` answers. */
function reply(overrides: Partial<AiTestResult> = {}): AiTestResult {
  return {
    requested_prompt_chars: 12,
    response: 'A port scan usually indicates reconnaissance.',
    model: 'llama3.2:3b',
    provider: 'ollama',
    prompt_tokens: 24,
    output_tokens: 14,
    duration_ms: 1_800,
    done_reason: 'stop',
    disclaimer: DISCLAIMER,
    ...overrides,
  }
}

/** Render the page with a toast recorder. */
function renderPage() {
  const showToast = vi.fn()
  const view = render(<AIConfiguration showToast={showToast} />)
  return { ...view, showToast }
}

/** The button that sends the test prompt. */
function sendButton(): HTMLElement {
  return screen.getByRole('button', { name: /send test prompt/i })
}

describe('AIConfiguration disabled state', () => {
  it('states that AI is switched off and asks for no inventory', async () => {
    const router = installFetch({
      'GET /ai/status': () =>
        ok(
          status({
            enabled: false,
            state: 'disabled',
            state_label: 'Disabled',
            state_description: 'Local AI is switched off by configuration.',
            runtime_reachable: false,
            model_available: false,
            runtime_version: '',
            installed_model_count: 0,
          }),
        ),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('Disabled')).toBeInTheDocument()
    })
    expect(screen.getByText(/switched off by configuration/i)).toBeInTheDocument()
    // The telling assertion: a disabled feature has no inventory to ask for, so the
    // request that would fail must never be sent.
    expect(router.countOf('GET /ai/models')).toBe(0)
    expect(screen.getByText(/the runtime is not answering/i)).toBeInTheDocument()
  })

  it('keeps the test form visible but unusable, with the reason stated', async () => {
    installFetch({
      'GET /ai/status': () =>
        ok(
          status({
            enabled: false,
            state: 'disabled',
            state_label: 'Disabled',
            state_description: 'Local AI is switched off by configuration.',
            runtime_reachable: false,
            model_available: false,
          }),
        ),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('Disabled')).toBeInTheDocument()
    })
    // Visible — the operator can see what the form will do once enabled…
    expect(screen.getByLabelText('Prompt')).toBeInTheDocument()
    // …and it cannot be sent, with the state named rather than left implicit.
    expect(sendButton()).toBeDisabled()
    expect(screen.getByText(/unavailable while the state is “disabled”/i)).toBeInTheDocument()
  })
})

describe('AIConfiguration runtime unavailable state', () => {
  it('reports an unreachable runtime without trying to list models', async () => {
    const router = installFetch({
      'GET /ai/status': () =>
        ok(
          status({
            state: 'unreachable',
            state_label: 'Runtime unreachable',
            state_description: 'Nothing answered at the configured local address.',
            runtime_reachable: false,
            model_available: false,
            runtime_version: '',
            installed_model_count: 0,
          }),
        ),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('Runtime unreachable')).toBeInTheDocument()
    })
    expect(router.countOf('GET /ai/models')).toBe(0)
    expect(sendButton()).toBeDisabled()
    // The status is still shown as a *state*, not as a failure of the page.
    expect(screen.queryByText(/the AI status could not be read/i)).toBeNull()
  })
})

describe('AIConfiguration model unavailable state', () => {
  it('names the missing model and offers no submission', async () => {
    installFetch({
      'GET /ai/status': () =>
        ok(
          status({
            state: 'model_missing',
            state_label: 'Model not installed',
            state_description: 'The runtime is running but the configured model is absent.',
            model_available: false,
          }),
        ),
      'GET /ai/models': () => ok(modelList([model({ name: 'qwen2.5:1.5b' })])),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('Model not installed')).toBeInTheDocument()
    })
    // The inventory is shown — the runtime answered, so there is one to show — and
    // the configured name is called out as absent from it.
    await waitFor(() => {
      expect(screen.getByText(/is not in\s+the inventory above/i)).toBeInTheDocument()
    })
    expect(sendButton()).toBeDisabled()
  })
})

describe('AIConfiguration ready state', () => {
  it('shows the configuration, the inventory and an enabled form', async () => {
    installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('Ready')).toBeInTheDocument()
    })
    expect(screen.getByText('ollama')).toBeInTheDocument()
    expect(screen.getByText('llama3.2:3b')).toBeInTheDocument()
    expect(screen.getByText(/runtime 0\.5\.7/)).toBeInTheDocument()

    await waitFor(() => {
      expect(screen.getByText('Q4_K_M')).toBeInTheDocument()
    })
    // 2.02 GB, from the byte count the runtime reported rather than a guess.
    expect(screen.getByText('2.02 GB')).toBeInTheDocument()
    expect(screen.getByText('in use')).toBeInTheDocument()
    // The probe budget is the backend's own number, shown rather than assumed:
    // "unreachable after 3s" and "unreachable after 60s" are different facts.
    expect(screen.getByText('3.0s')).toBeInTheDocument()
    expect(sendButton()).toBeEnabled()
  })

  it('shows no probe budget when the backend reports none', async () => {
    // A payload without a budget renders an em dash rather than a misleading 0.0s.
    installFetch({
      'GET /ai/status': () => ok(status({ health_timeout_seconds: 0 })),
      'GET /ai/models': () => ok(modelList([model()])),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('Probe budget')).toBeInTheDocument()
    })
    const cell = screen.getByText('Probe budget').parentElement
    expect(cell).not.toBeNull()
    expect(within(cell as HTMLElement).getByText('—')).toBeInTheDocument()
    expect(screen.queryByText('0.0s')).toBeNull()
  })

  it('reads the status once and the inventory once', async () => {
    const router = installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
    })
    renderPage()

    await waitFor(() => {
      expect(router.countOf('GET /ai/models')).toBe(1)
    })
    expect(router.countOf('GET /ai/status')).toBe(1)
  })

  it('reports a failed inventory without hiding the state', async () => {
    installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () =>
        failure(503, 'The model inventory could not be read.', [
          { field: 'runtime', code: 'AI_UNAVAILABLE' },
        ]),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText(/model list could not be read/i)).toBeInTheDocument()
    })
    // The status call answered, so the state is still reported truthfully.
    expect(screen.getByText('Ready')).toBeInTheDocument()
  })
})

describe('AIConfiguration test generation', () => {
  it('sends the trimmed prompt and nothing else', async () => {
    const router = installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
      'POST /ai/test': () => ok(reply()),
    })
    renderPage()

    await waitFor(() => {
      expect(sendButton()).toBeEnabled()
    })

    fireEvent.change(screen.getByLabelText('Prompt'), {
      target: { value: '  What is a SYN flood?  ' },
    })
    fireEvent.click(sendButton())

    await waitFor(() => {
      expect(router.countOf('POST /ai/test')).toBe(1)
    })
    // Exactly one field. A model, host or timeout here would mean the browser had
    // gained a choice the backend deliberately does not offer.
    expect(router.lastCall('POST /ai/test')?.body).toEqual({ prompt: 'What is a SYN flood?' })
  })

  it('renders the reply as text with its disclaimer', async () => {
    installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
      'POST /ai/test': () =>
        ok(reply({ response: '<script>alert(1)</script> is not markup here.' })),
    })
    renderPage()

    await waitFor(() => {
      expect(sendButton()).toBeEnabled()
    })
    fireEvent.click(sendButton())

    await waitFor(() => {
      expect(screen.getByText('Generated reply')).toBeInTheDocument()
    })
    // The tag is literal text: no element named `script` was created from it.
    expect(screen.getByText(/<script>alert\(1\)<\/script> is not markup here\./)).toBeInTheDocument()
    expect(document.querySelector('script')).toBeNull()
    // The sentence saying what the text is travels with the text.
    expect(screen.getByText(DISCLAIMER)).toBeInTheDocument()
    expect(screen.getByText('14 tok')).toBeInTheDocument()
    expect(screen.getByText('1.8s')).toBeInTheDocument()
  })

  it('says a reply was cut off when the output budget stopped it', async () => {
    installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
      'POST /ai/test': () => ok(reply({ done_reason: 'length' })),
    })
    const { showToast } = renderPage()

    await waitFor(() => {
      expect(sendButton()).toBeEnabled()
    })
    fireEvent.click(sendButton())

    await waitFor(() => {
      expect(screen.getByText('cut off at the output limit')).toBeInTheDocument()
    })
    expect(showToast).toHaveBeenCalledWith(
      'The model stopped at the output limit, so the reply may be cut off.',
      'info',
    )
  })

  it('shows a working state and refuses a second submission while one is in flight', async () => {
    let release: ((value: Response) => void) | undefined
    const router = installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
      'POST /ai/test': () =>
        new Promise<Response>(resolve => {
          release = resolve
        }),
    })
    renderPage()

    await waitFor(() => {
      expect(sendButton()).toBeEnabled()
    })
    fireEvent.click(sendButton())

    await waitFor(() => {
      expect(screen.getByText('Working…')).toBeInTheDocument()
    })
    // Disabled while running, so a double click cannot send the inference twice.
    expect(screen.getByRole('button', { name: /working/i })).toBeDisabled()
    fireEvent.click(screen.getByRole('button', { name: /working/i }))
    expect(router.countOf('POST /ai/test')).toBe(1)

    release?.(ok(reply()))
    await waitFor(() => {
      expect(screen.getByText('Generated reply')).toBeInTheDocument()
    })
  })

  it('reports a timed-out generation without claiming a reply arrived', async () => {
    installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
      'POST /ai/test': () =>
        failure(503, 'The model did not answer within the configured timeout.', [
          { field: 'timeout', code: 'AI_TIMEOUT' },
        ]),
    })
    renderPage()

    await waitFor(() => {
      expect(sendButton()).toBeEnabled()
    })
    fireEvent.click(sendButton())

    await waitFor(() => {
      expect(screen.getByText('The test did not produce a reply')).toBeInTheDocument()
    })
    expect(
      screen.getByText('The model did not answer within the configured timeout.'),
    ).toBeInTheDocument()
    expect(screen.queryByText('Generated reply')).toBeNull()
  })

  it('distinguishes a disabled runtime from a generation failure', async () => {
    installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
      'POST /ai/test': () =>
        failure(503, 'Local AI is switched off, so nothing was generated.', [
          { field: 'llm_enabled', code: 'AI_DISABLED' },
        ]),
    })
    renderPage()

    await waitFor(() => {
      expect(sendButton()).toBeEnabled()
    })
    fireEvent.click(sendButton())

    await waitFor(() => {
      expect(screen.getByText('The test did not produce a reply')).toBeInTheDocument()
    })
    // The backend's own sentence is repeated unchanged — the page does not decide
    // which of the four 503 causes it was.
    expect(
      screen.getByText('Local AI is switched off, so nothing was generated.'),
    ).toBeInTheDocument()
  })
})

describe('AIConfiguration failure states', () => {
  it('shows a busy panel while the first status request is in flight', () => {
    installFetch({ 'GET /ai/status': () => new Promise<Response>(() => {}) })
    renderPage()
    expect(screen.getByText('Checking the runtime…')).toBeInTheDocument()
  })

  it('offers a retry when the status request itself fails', async () => {
    vi.stubGlobal('fetch', networkDownFetch())
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('The AI status could not be read')).toBeInTheDocument()
    })
    // A failed request is stated as exactly that — not as a missing model.
    expect(screen.getByText(/not a missing model/i)).toBeInTheDocument()
    expect(screen.getByRole('button', { name: /retry/i })).toBeInTheDocument()
    // Nothing is claimed about a runtime that was never reached.
    expect(screen.queryByText('Ready')).toBeNull()
  })

  it('re-checks on request and reflects the new state', async () => {
    let attempts = 0
    const router = installFetch({
      'GET /ai/status': () => {
        attempts += 1
        return ok(
          attempts === 1
            ? status({
                state: 'unreachable',
                state_label: 'Runtime unreachable',
                state_description: 'Nothing answered at the configured local address.',
                runtime_reachable: false,
                model_available: false,
              })
            : status(),
        )
      },
      'GET /ai/models': () => ok(modelList([model()])),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('Runtime unreachable')).toBeInTheDocument()
    })

    fireEvent.click(screen.getByRole('button', { name: /re-check/i }))

    await waitFor(() => {
      expect(screen.getByText('Ready')).toBeInTheDocument()
    })
    expect(router.countOf('GET /ai/status')).toBe(2)
    // The inventory is asked for only once the retry says the runtime is up.
    await waitFor(() => {
      expect(router.countOf('GET /ai/models')).toBe(1)
    })
  })

  it('does not offer a submission for a blank prompt', async () => {
    installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
    })
    renderPage()

    await waitFor(() => {
      expect(sendButton()).toBeEnabled()
    })
    fireEvent.change(screen.getByLabelText('Prompt'), { target: { value: '   ' } })
    expect(sendButton()).toBeDisabled()
  })

  it('repeats the prompt length so the operator sees the bounded size', async () => {
    installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByLabelText('Prompt')).toBeInTheDocument()
    })
    const box = screen.getByLabelText('Prompt')
    expect(screen.getByText(new RegExp(`^${(box as HTMLTextAreaElement).value.length} characters`)))
      .toBeInTheDocument()
  })
})

describe('AIConfiguration scope disclosure', () => {
  it('states that nothing here affects detections, alerts or risk', async () => {
    installFetch({
      'GET /ai/status': () => ok(status()),
      'GET /ai/models': () => ok(modelList([model()])),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('AI Configuration')).toBeInTheDocument()
    })
    expect(
      screen.getByText(/no alert is explained here and no detection,\s*incident or risk score is affected/i),
    ).toBeInTheDocument()
  })

  it('marks the inventory count from the payload rather than the array length', async () => {
    installFetch({
      'GET /ai/status': () => ok(status({ installed_model_count: 7 })),
      // The listing is narrower than the status's count, as a runtime that gained a
      // model between the two calls would report. The page must show the listing's
      // own count beside the listing, not the status's.
      'GET /ai/models': () => ok(modelList([model()], { count: 1 })),
    })
    renderPage()

    await waitFor(() => {
      expect(screen.getByText('Q4_K_M')).toBeInTheDocument()
    })
    // The section heading, not the "Installed models" fact in the configuration
    // grid — that one carries the status payload's own count, and this test is
    // about which payload the table's badge reads.
    const section = screen.getByRole('heading', { name: 'Installed models' }).parentElement
    expect(section).not.toBeNull()
    expect(within(section as HTMLElement).getByText('1')).toBeInTheDocument()
  })
})
