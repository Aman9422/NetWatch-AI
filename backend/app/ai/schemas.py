"""Wire schemas for the local LLM API (M23.9).

Three payloads, and each carries the same sentence about what it is not. The
disclaimer is stated once, here, so the API, the page and the documentation cannot
drift apart — the pattern M22 uses for its anomaly warning and M21 for its baseline
description.

**What these schemas refuse to claim.** Nothing here is a security judgement, a
risk score or an analysis. The test endpoint returns text a language model
produced, and a reader who mistakes that for an assessment would be making the one
error this milestone's disclaimer exists to prevent (M23.9/M23.16).
"""

from __future__ import annotations

from pydantic import BaseModel, Field

#: The sentence every payload in this module carries (M23.9). Stated once.
LLM_DISCLAIMER = (
    "This text was generated by a local language model. It is not a security "
    "finding, not an analysis of your traffic, and may be incorrect. M23 "
    "implements the integration only; no model output affects detection, alerts, "
    "incidents or risk scores."
)

#: Human labels for the four states, for a badge (M23.11).
STATE_LABELS: dict[str, str] = {
    "disabled": "Disabled",
    "unreachable": "Runtime unreachable",
    "model_missing": "Model missing",
    "ready": "Ready",
}


class AiStatusData(BaseModel):
    """Payload of ``GET /api/v1/ai/status`` (M23.9).

    Attributes:
        enabled: Whether ``llm_enabled`` is true. **This is the authoritative
            switch**, deliberately distinct from the database row named
            ``ai_enabled`` that ``/api/v1/settings`` exposes.
        provider: The configured runtime, e.g. ``ollama``.
        model: The configured model, blank when none is set.
        state: ``disabled``, ``unreachable``, ``model_missing`` or ``ready``.
        state_label: Short badge text for the state.
        state_description: One sentence explaining it and what to do.
        runtime_reachable: Whether the runtime answered the health probe.
        model_available: Whether the configured model is installed.
        runtime_version: The runtime's version string, when it reported one.
        installed_model_count: How many models it reports, when reachable.
        message: A safe sentence for the page. Never a provider error, URL or path.
        health_timeout_seconds: The budget the probe used, so an operator can see
            why a check answered quickly or not at all.
        disclaimer: The sentence stating what model output is and is not.
    """

    enabled: bool
    provider: str
    model: str
    state: str
    state_label: str
    state_description: str
    runtime_reachable: bool
    model_available: bool
    runtime_version: str = ""
    installed_model_count: int = 0
    message: str = ""
    health_timeout_seconds: float = 0.0
    disclaimer: str = LLM_DISCLAIMER


class AiModelView(BaseModel):
    """One installed model (M23.8).

    A projection of what the runtime reports, not a curated list: if the runtime
    has four models, four are returned.

    Attributes:
        name: The identifier to name in ``LLM_MODEL``.
        parameter_size: e.g. ``3.2B``, when reported.
        quantization: e.g. ``Q4_K_M``, when reported.
        size_bytes: On-disk size, when reported.
        family: e.g. ``llama``, when reported.
    """

    name: str
    parameter_size: str = ""
    quantization: str = ""
    size_bytes: int = 0
    family: str = ""


class AiModelListData(BaseModel):
    """Payload of ``GET /api/v1/ai/models`` (M23.8).

    Attributes:
        count: How many models this response carries.
        configured_model: The model named in configuration, so a page can mark it.
        configured_model_installed: Whether that model is among ``models``.
        models: The installed models, as the runtime reports them.
        disclaimer: The sentence stating what model output is and is not.
    """

    count: int = 0
    configured_model: str = ""
    configured_model_installed: bool = False
    models: list[AiModelView] = Field(default_factory=list)
    disclaimer: str = LLM_DISCLAIMER


class AiTestRequest(BaseModel):
    """Body of ``POST /api/v1/ai/test`` (M23.9).

    **Only a prompt.** There is deliberately no field for a model, a host, a
    timeout, a context size or a temperature: those are configuration, and a body
    that could set them would let a client choose which model runs and where it is
    reached — what M23.10 forbids.

    ``max_length`` is a second fence in front of the service's own check. It is
    deliberately generous (the service enforces the configured, lower limit) so a
    prompt refused here is clearly malformed rather than merely at the operator's
    configured ceiling.
    """

    prompt: str = Field(
        min_length=1,
        max_length=8000,
        description=(
            "Text to send to the configured model. The operator's configured "
            "limit may be lower; that limit is enforced by the service."
        ),
    )


class AiTestData(BaseModel):
    """Payload of ``POST /api/v1/ai/test`` (M23.9).

    Attributes:
        requested_prompt_chars: How long the accepted prompt was, so the page can
            confirm what was sent without echoing it back.
        response: The model's reply. **Untrusted text** — rendered, never executed.
        model: The model that produced it.
        provider: The runtime that served it.
        prompt_tokens / output_tokens: Token counts, when the runtime reported them.
        duration_ms: Wall time the runtime spent, when reported.
        done_reason: ``stop`` for a finished reply, ``length`` when the output
            budget cut it off.
        disclaimer: The sentence stating what this text is and is not.
    """

    requested_prompt_chars: int = 0
    response: str
    model: str = ""
    provider: str = ""
    prompt_tokens: int = 0
    output_tokens: int = 0
    duration_ms: float = 0.0
    done_reason: str = ""
    disclaimer: str = LLM_DISCLAIMER


